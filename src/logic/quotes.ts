/** 日付ベースで安定して1つ選ぶ（同じ日は同じ格言） */
export function quoteOfToday(dateStr: string): { text: string; sub?: string } {
  let h = 0;
  for (let i = 0; i < dateStr.length; i++) h = (h * 31 + dateStr.charCodeAt(i)) >>> 0;
  return QUOTES[h % QUOTES.length];
}

