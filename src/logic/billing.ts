/**
 * 課金（モック）— 案C: カード登録＋失敗時のみ課金（お金は預からない）。
 * 実際の決済は行わない。将来 Stripe を差し込む前提の設計。
 *
 * モデル（Beeminder型・コミットメント料金）:
 *  - 開始時にカードを登録し、コミット額を「宣言」する（この時点では課金しない）
 *  - 4週間を週ごとに分割（週ぶん = コミット額 / 4）
 *  - その週の目標を達成 → その週ぶんは免除（¥0）
 *  - 未達 → その週ぶんだけ後からカードに課金される（＝痛み）
 *  - 完全達成すれば1円も課金されない（続けた人は無料）
 *  - 課金額（未達ぶん）が運営の収益。利用者間での再分配はしない（賭博回避）
 *  - "罰金" ではなく "達成で免除される料金" として設計（消費者契約法対策）
 */

/** コミット額の選択肢（未達の週ぶんだけ課金・モック） */
export const DEPOSIT_OPTIONS = [400, 1200, 4000, 12000];

/** コミット額のデフォルト */
export const DEFAULT_DEPOSIT = 1200;

/** 1週間ぶんの課金対象額（コミット額 / 週数） */
export function weekStake(deposit: number, weeks: number): number {
  return Math.round(deposit / weeks);
}
